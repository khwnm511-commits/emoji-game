def custom_entities(text: str, indices: list[int]):
    """ساخت entityهای ایموجی سفارشی برای متن — تلگرام"""
    from aiogram.types import MessageEntity
    ents = []
    pos = 0
    for i in indices:
        e, cid = emoji_by_index(i)
        idx = text.find(e, pos)
        if idx >= 0:
            ents.append(MessageEntity(type="custom_emoji", offset=idx, length=len(e), custom_emoji_id=cid))
            pos = idx + len(e)
    return ents
